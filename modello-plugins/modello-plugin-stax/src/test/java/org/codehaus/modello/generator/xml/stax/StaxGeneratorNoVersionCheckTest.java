package org.codehaus.modello.generator.xml.stax;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Map;

import org.codehaus.modello.model.Model;
import org.codehaus.plexus.component.repository.exception.ComponentLookupException;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Tests that {@code modello.stax.versionCheck=false} leaves the version check out of the generated reader.
 */
public class StaxGeneratorNoVersionCheckTest extends AbstractStaxGeneratorTestCase {
    private static final String CHECK_MESSAGE = "doesn't match reader version";

    public StaxGeneratorNoVersionCheckTest() throws ComponentLookupException {
        super("stax-no-version-check");
    }

    @Test
    public void testReaderWithoutVersionCheck() throws Throwable {
        Model model = modello.loadModel(getXmlResourceReader("/version-in-namespace.mdo"));

        Map<String, Object> parameters = getModelloParameters("4.0.0");
        parameters.put("modello.stax.versionCheck", "false");

        modello.generate(model, "java", parameters);
        modello.generate(model, "stax-reader", parameters);

        String source = readGeneratedReader();
        assertFalse(source.contains(CHECK_MESSAGE), "version check must not be generated");

        compileGeneratedSources();

        verifyCompiledGeneratedSources("org.codehaus.modello.generator.xml.stax.StaxVerifierNoVersionCheck");
    }

    @Test
    public void testReaderWithVersionCheckByDefault() throws Throwable {
        Model model = modello.loadModel(getXmlResourceReader("/version-in-namespace.mdo"));

        Map<String, Object> parameters = getModelloParameters("4.0.0");

        modello.generate(model, "java", parameters);
        modello.generate(model, "stax-reader", parameters);

        assertTrue(readGeneratedReader().contains(CHECK_MESSAGE), "version check must be generated by default");
    }

    private String readGeneratedReader() throws Exception {
        File reader = new File(
                getOutputDirectory(), "org/codehaus/modello/test/model/vin/io/stax/VersionInNamespaceStaxReader.java");
        return new String(Files.readAllBytes(reader.toPath()), StandardCharsets.UTF_8);
    }
}
